"""Data files of the home page (docs/index.html), exported from a CaMa-Flood-GPU run.

    python tools/home_data.py --params .../inp/glb_15min/parameters.nc \
        --run .../out/glb_15min_e2o --runoff .../e2o_ecmwf_wrr2_glob15_day_Runoff_2000.nc \
        --hires .../map/glb_15min/1min --forcing "daily eartH2Observe WRR2 runoff (ECMWF HTESSEL, 0.25°)" \
        --spin-up-years 1

The run directory must hold one year of daily `total_outflow_mean` and `river_depth_mean`
and the monthly `total_outflow_max_mean` for all catchments (`*_rank*.nc`); --runoff is
the forcing file of that year and --hires the 1-arcmin maps of the CaMa-Flood map
(`1min.catmxy.bin`, `1min.uparea.bin`, `1min.downxy.bin`). Writes two small scripts to
docs/home/data/:

    rivers.js      the river network as reaches with daily mean discharge (hero map), the
                   GPU of each basin (multi-GPU figure), the daily discharge at all river
                   mouths (hero sparkline), the main stems of well-known rivers and the
                   annual mean runoff of the forcing on a coarse grid (runoff figure)
    hydrograph.js  daily mean outflow and river depth, monthly maximum outflow and the
                   channel and floodplain parameters at gauges on some of those rivers,
                   and the unit catchments and rivers around the last gauge on the
                   1-arcmin map with the daily discharge of each between its own low and
                   high water of the year (storage figure)

The network keeps catchments with an upstream area of at least --min-upstream-km2. A
reach is a chain of catchments with one upstream catchment each and one upstream-area
class; it is stored as a polyline of outlet positions (0.05 degree steps) and carries
the daily mean discharge at its downstream end on a log scale in 4 bits, packed as runs
(see pack_levels); reaches of the larger rivers also carry it in 32 steps between their
own lowest and highest daily discharge, which the hero map reads out under the pointer.
Basins go to GPUs largest first, each to the least loaded GPU, as CaMa-Flood-GPU reports
its loads. A main stem is traced from the largest catchment near
the given mouth up through the upstream catchment with the largest area.
"""

